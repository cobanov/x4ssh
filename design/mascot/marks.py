def grid(text):
    rows = text.strip('\n').split('\n')
    w = max(map(len, rows))
    return np.array([[c == '#' for c in r.ljust(w, '.')] for r in rows])

def wordmark(gap=2):
    gs = [grid(GLYPHS[c]) for c in 'x4ssh']
    h = max(g.shape[0] for g in gs)
    cols = []
    for i, g in enumerate(gs):
        cols.append(g)
        if i < len(gs) - 1: cols.append(np.zeros((h, gap), bool))
    return np.hstack(cols)
